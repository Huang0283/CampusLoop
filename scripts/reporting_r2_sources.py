"""Rebuild R2's source inventory from immutable Git objects and validate LaTeX/figure artifacts."""
import ast
import json
import re
import subprocess
from pathlib import Path

SHA = 'ecc22d2cb2e54de1e5ffa05ffa71b8df1ab9a1b6'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/submission/technical-report/latex'


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT).decode('utf-8')


def read(path):
    return git('show', f'{SHA}:{path}')


def link(path, line):
    return f'https://github.com/Huang0283/CampusLoop/blob/{SHA}/{path}#L{line}'


def strip_comments(text: str) -> str:
    lines = []
    for line in text.splitlines():
        cleaned = re.sub(r'(?<!\\)%.*$', '', line)
        lines.append(cleaned)
    return '\n'.join(lines)


def strip_math_and_tables(text: str) -> str:
    # Remove display equations, inline math, and table column separators so prose escaping stays strict.
    text = re.sub(r'\\begin\{equation\}.*?\\end\{equation\}', ' ', text, flags=re.S)
    text = re.sub(r'\\begin\{align\*?\}.*?\\end\{align\*?\}', ' ', text, flags=re.S)
    text = re.sub(r'\\\[.*?\\\]', ' ', text, flags=re.S)
    text = re.sub(r'(?<!\\)\$.*?(?<!\\)\$', ' ', text, flags=re.S)
    # Inside tabular/tabularx/longtable, '&' is a valid column separator, not an unescaped prose ampersand.
    def _clean_table_ampersands(match):
        return match.group(0).replace('&', ' ')
    text = re.sub(
        r'\\begin\{(?:tabularx?|longtable)\}.*?\\end\{(?:tabularx?|longtable)\}',
        _clean_table_ampersands,
        text,
        flags=re.S,
    )
    return text


def main():
    classes = {}
    paths = git('ls-tree', '-r', '--name-only', SHA, 'backend/app/models').splitlines()
    for path in paths:
        if not path.endswith('.py'):
            continue
        src = read(path)
        for node in ast.parse(src).body:
            if not isinstance(node, ast.ClassDef):
                continue
            fields, table = [], None
            for item in node.body:
                if isinstance(item, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__tablename__' for t in item.targets):
                    table = ast.literal_eval(item.value)
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    fields.append({
                        'name': item.target.id,
                        'annotation': ast.unparse(item.annotation),
                        'definition': ast.unparse(item.value) if item.value else '',
                        'line': item.lineno,
                    })
            if table:
                classes[node.name] = {'table': table, 'path': path, 'line': node.lineno, 'fields': fields}
    migrations = []
    for path in git('ls-tree', '-r', '--name-only', SHA, 'backend/alembic/versions').splitlines():
        if path.endswith('.py'):
            src = read(path)
            tree = ast.parse(src)
            upgrade = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'upgrade')
            migrations.append({'path': path, 'line': upgrade.lineno, 'upgrade': ast.get_source_segment(src, upgrade)})
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'r2-source-inventory.json').write_text(
        json.dumps({'software_sha': SHA, 'classes': classes, 'migrations': migrations}, indent=2) + '\n',
        encoding='utf-8',
    )
    rows = [
        '# R2 model and migration inventory',
        '',
        f'Software baseline: `{SHA}`. Generated by `python scripts/reporting_r2_sources.py`.',
        '',
        'This is an exact source inventory extracted from immutable Git objects; no live database is accessed. ORM annotations and effective migration constraints must be read together. Complete `upgrade()` bodies are preserved in `r2-source-inventory.json`.',
        '',
        '## Critical reconciliation',
        '',
        '- Migration 0003 makes `orders.offer_id` unique and adds partial unique `product_id` for `status NOT IN (\'CANCELLED\', \'DISPUTED\')`. A product can accumulate historical orders while retaining at most one active reservation or completed sale.',
        '- Migration 0003 makes `chat_messages.client_msg_id` non-null and unique per `(sender_id, client_msg_id)` even though the ORM annotation is optional.',
        '- Migration 0012 makes `account_appeals.decision_id` non-null and unique; ORM inference alone must not be used to draw optional parentage.',
        '- Migration 0013 limits duplicate report protection to `PENDING`/`PROCESSING`; handled history does not block a later report.',
        '- `Report.target_id` is an application-validated polymorphic identifier, not a SQL foreign key.',
        '',
        '## Model classes and fields',
    ]
    for name, info in classes.items():
        rows += [
            '',
            f'### {name} — {info["table"]}',
            '',
            f'[Class definition]({link(info["path"], info["line"])})',
            '',
            '| Member | Python annotation | SQLAlchemy definition |',
            '|---|---|---|',
        ]
        for f in info['fields']:
            rows.append(
                f'| [{f["name"]}]({link(info["path"], f["line"])}) | `{f["annotation"].replace("|", "&#124;")}` | `{f["definition"].replace("|", "&#124;")}` |'
            )
    rows += ['', '## Migration chain 0001–0013', '']
    for m in migrations:
        rows.append(f'- [{m["path"]}]({link(m["path"], m["line"])}) — complete `upgrade()` retained in the JSON inventory.')
    (OUT / 'r2-model-migration-index.md').write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f'Inventoried {len(classes)} real ORM classes and {len(migrations)} migrations at {SHA}')

    figures = OUT / 'figures/design'
    sources = sorted(figures.glob('*.mmd'))
    assert len(sources) == 9, 'Expected nine maintained diagram sources'
    for source in sources:
        for suffix in ('.svg', '.pdf'):
            target = source.with_suffix(suffix)
            assert target.exists() and target.stat().st_size > 100, str(target)

    chapter_paths = sorted((OUT / 'chapters').glob('*.tex'))
    all_tex = '\n'.join(strip_comments(p.read_text(encoding='utf-8')) for p in chapter_paths)
    for name in re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}', all_tex):
        assert (OUT / name).exists(), name

    for tex in chapter_paths:
        text = strip_comments(tex.read_text(encoding='utf-8'))
        depth = 0
        for brace in re.findall(r'(?<!\\)[{}]', text):
            depth += 1 if brace == '{' else -1
            assert depth >= 0, f'Unbalanced braces in {tex.name}'
        assert depth == 0, f'Unbalanced braces in {tex.name}'
        prose = strip_math_and_tables(text)
        # Strip \label{...}, \ref{...}, \cite{...}, \includegraphics{...} which legitimately contain hyphens/underscores.
        prose_clean = re.sub(r'\\(?:label|ref|cite|includegraphics(?:\[[^\]]*\])?)\{[^}]*\}', '', prose)
        bad = re.search(r'(?<!\\)[_&#%]', prose_clean)
        assert not bad, f'Unescaped special character {bad.group(0)!r} in {tex.name}: {prose_clean[max(0, bad.start()-30):bad.end()+30]!r}'

    labels = set(re.findall(r'\\label\{([^}]+)\}', all_tex))
    refs = set(re.findall(r'\\ref\{([^}]+)\}', all_tex))
    assert refs <= labels, f'Undefined refs: {refs - labels}'

    bib_text = (OUT / 'r2-references.bib').read_text(encoding='utf-8')
    bib_keys = set(re.findall(r'@\w+\{([^,\s]+),', bib_text))
    cited_keys = set()
    for match in re.findall(r'\\cite\{([^}]+)\}', all_tex):
        for key in match.split(','):
            cited_keys.add(key.strip())
    assert cited_keys <= bib_keys, f'Missing bib keys: {cited_keys - bib_keys}'
    assert bib_keys <= cited_keys, f'Uncited bib keys: {bib_keys - cited_keys}'

    sdk = read('frontend/src/sdk/generated/sdk.gen.ts')
    for operation in (
        'uploadImage', 'createProduct', 'restoreBrowserSession', 'sendMessage',
        'acceptOffer', 'saveMeetup', 'confirmMeetup', 'confirmOrderComplete',
        'createReview', 'resolveReport', 'overrideReport',
        'adminCreateAccountDecision', 'submitAccountAppeal', 'adminReviewAccountAppeal',
    ):
        assert operation in sdk, operation
    for name in ('User', 'Product', 'ChatSession', 'Offer', 'Order', 'Meetup'):
        assert name in classes
    assert len(migrations) == 13
    print(f'PASS: 9 figures, {len(bib_keys)} cited refs, 27 ORM classes, 13 migrations, 14 SDK ops, clean LaTeX escaping')


if __name__ == '__main__':
    main()
