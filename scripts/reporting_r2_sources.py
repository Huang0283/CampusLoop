"""Rebuild R2's source inventory from immutable Git objects; no application writes."""
import ast
import json
import subprocess
import re
from pathlib import Path

SHA = 'edb9e32871eac2966750993294078acbfdba65f9'
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/submission/technical-report/latex'


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT).decode('utf-8')


def read(path):
    return git('show', f'{SHA}:{path}')


def link(path, line):
    return f'https://github.com/Huang0283/CampusLoop/blob/{SHA}/{path}#L{line}'


def main():
    classes = {}
    paths = git('ls-tree', '-r', '--name-only', SHA, 'backend/app/models').splitlines()
    for path in paths:
        if not path.endswith('.py'):
            continue
        src = read(path)
        for node in ast.parse(src).body:
            if not isinstance(node, ast.ClassDef):
                continue
            fields, table = [], None
            for item in node.body:
                if isinstance(item, ast.Assign) and any(isinstance(t, ast.Name) and t.id == '__tablename__' for t in item.targets):
                    table = ast.literal_eval(item.value)
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    fields.append({'name': item.target.id, 'annotation': ast.unparse(item.annotation), 'definition': ast.unparse(item.value) if item.value else '', 'line': item.lineno})
            if table:
                classes[node.name] = {'table': table, 'path': path, 'line': node.lineno, 'fields': fields}
    migrations = []
    for path in git('ls-tree', '-r', '--name-only', SHA, 'backend/alembic/versions').splitlines():
        if path.endswith('.py'):
            src = read(path)
            tree = ast.parse(src)
            upgrade = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'upgrade')
            migrations.append({'path': path, 'line': upgrade.lineno, 'upgrade': ast.get_source_segment(src, upgrade)})
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'r2-source-inventory.json').write_text(json.dumps({'software_sha': SHA, 'classes': classes, 'migrations': migrations}, indent=2) + '\n', encoding='utf-8')
    rows = ['# R2 model and migration inventory', '', f'Software baseline: `{SHA}`. Generated by `python scripts/reporting_r2_sources.py`.', '', 'This is an exact source inventory, not a database inspection. ORM annotations and effective migration constraints must be read together. Full upgrade bodies are retained in `r2-source-inventory.json`; no production database is accessed.', '', '## Critical reconciliation', '', '- Migration 0003 makes `orders.offer_id` unique and adds partial unique `product_id` for status NOT IN CANCELLED/DISPUTED. A product can have multiple historical orders.', '- Migration 0003 makes message client IDs non-null and unique per sender even though the ORM annotation is optional.', '- Migration 0012 makes `account_appeals.decision_id` non-null and unique; ORM inference alone must not be used to draw optional parentage.', '- Migration 0013 limits duplicate report protection to PENDING/PROCESSING; handled history does not prevent a later report.', '- `Report.target_id` is a polymorphic identifier, not a declared foreign key.', '', '## Model classes and fields']
    for name, info in classes.items():
        rows += ['', f'### {name} — {info["table"]}', '', f'[Class definition]({link(info["path"], info["line"])})', '', '| Member | Python annotation | SQLAlchemy definition |', '|---|---|---|']
        for f in info['fields']:
            rows.append(f'| [{f["name"]}]({link(info["path"], f["line"])}) | `{f["annotation"].replace("|", "&#124;")}` | `{f["definition"].replace("|", "&#124;")}` |')
    rows += ['', '## Migration chain 0001–0013', '']
    for m in migrations:
        rows.append(f'- [{m["path"]}]({link(m["path"], m["line"])}) — complete `upgrade()` retained in the JSON inventory.')
    (OUT / 'r2-model-migration-index.md').write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f'Inventoried {len(classes)} real ORM classes and {len(migrations)} migrations at {SHA}')
    figures = OUT / 'figures/design'
    sources = sorted(figures.glob('*.mmd'))
    assert len(sources) == 9, 'Expected nine maintained diagram sources'
    for source in sources:
        for suffix in ('.svg', '.pdf'):
            target = source.with_suffix(suffix)
            assert target.exists() and target.stat().st_size > 100, str(target)
    all_tex = '\n'.join(p.read_text(encoding='utf-8') for p in (OUT / 'chapters').glob('*.tex'))
    for name in re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}', all_tex):
        assert (OUT / name).exists(), name
    for tex in (OUT / 'chapters').glob('*.tex'):
        text = tex.read_text(encoding='utf-8')
        depth = 0
        for brace in re.findall(r'(?<!\\)[{}]', text):
            depth += 1 if brace == '{' else -1
            assert depth >= 0, tex.name
        assert depth == 0, tex.name
        assert not re.search(r'(?<!\\)[_&#%]', text), tex.name
    labels = set(re.findall(r'\\label\{([^}]+)\}', all_tex))
    assert set(re.findall(r'\\ref\{([^}]+)\}', all_tex)) <= labels
    sdk = read('frontend/src/sdk/generated/sdk.gen.ts')
    for operation in ('uploadImage', 'createProduct', 'restoreBrowserSession', 'sendMessage', 'acceptOffer', 'saveMeetup', 'confirmMeetup', 'confirmOrderComplete', 'createReview', 'resolveReport', 'overrideReport', 'adminCreateAccountDecision', 'submitAccountAppeal', 'adminReviewAccountAppeal'):
        assert operation in sdk, operation
    for name in ('Product', 'ChatSession', 'Offer', 'Order', 'Meetup'):
        assert name in classes
    assert len(migrations) == 13
    print('PASS: exports, chapter paths/braces/labels/escaping, real ORM class names and 14 SDK operations')


if __name__ == '__main__':
    main()
