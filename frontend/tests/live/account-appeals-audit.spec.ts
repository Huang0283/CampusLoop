import { test, expect } from './fixtures'
import { randomUUID } from 'node:crypto'

const auditApi = process.env.CAMPUSLOOP_APPEAL_AUDIT_API

test('real warning, private appeal, disable notice and restored login (isolated audit only)', async ({ browser }) => {
  test.skip(!auditApi, 'Requires an explicitly selected audit API and audit frontend')
  expect(process.env.CAMPUSLOOP_TEST_API_CONTAINER).toMatch(/audit/)
  expect(process.env.CAMPUSLOOP_UI_URL).not.toBe('http://127.0.0.1:5174')
  const studentContext = await browser.newContext(), adminContext = await browser.newContext()
  const student = await studentContext.newPage(), admin = await adminContext.newPage()
  const errors: string[] = []
  for (const page of [student, admin]) page.on('pageerror', error => errors.push(error.name))
  const email = `appeal-e2e-${randomUUID()}@example.invalid`
  const password = `Appeal-${randomUUID()}`
  await student.goto('/register')
  await student.getByLabel('校园邮箱', { exact: true }).fill(email)
  await student.getByLabel('昵称', { exact: true }).fill('申诉流程验收')
  await student.getByLabel('密码', { exact: true }).fill(password)
  const registered = student.waitForResponse(response => response.url() === `${auditApi}/auth/register`)
  await student.getByRole('button', { name: '注册并登录', exact: true }).click()
  const userId = (await (await registered).json()).data.user.id
  await expect(student).toHaveURL(/\/market$/)
  await admin.goto('/login')
  await admin.getByLabel('校园邮箱', { exact: true }).fill('admin.demo@example.com')
  await admin.getByLabel('密码', { exact: true }).fill('Demo@12345')
  await admin.getByRole('button', { name: '登录', exact: true }).click()
  await expect(admin).toHaveURL(/\/admin$/)
  const users = admin.waitForResponse(response => response.url().includes('/admin/users?') && response.status() === 200)
  await admin.goto('/admin/users')
  const total = (await (await users).json()).data.pagination.total
  const last = Math.ceil(total / 20)
  if (last > 1) await admin.locator(`.ant-pagination-item-${last}`).click()
  await admin.getByRole('button', { name: `详情与人工处理 #${userId}`, exact: true }).click()
  const userDialog = admin.getByRole('dialog', { name: '用户详情与风险复核', exact: true })
  await userDialog.getByLabel('处理方式', { exact: true }).click()
  await admin.getByRole('option', { name: '发出违规警告', exact: true }).click()
  await userDialog.getByLabel('相关行为与事实', { exact: true }).fill('独立审计：商品描述存在待核实内容。')
  await userDialog.getByLabel('处理依据', { exact: true }).fill('独立审计：商品信息规则。')
  await userDialog.getByLabel('状态变更原因', { exact: true }).fill('独立审计警告，请补充说明。')
  const warningSaved = admin.waitForResponse(response => response.url() === `${auditApi}/admin/users/${userId}/decisions` && response.request().method() === 'POST')
  await userDialog.getByRole('button', { name: '发出违规警告', exact: true }).click()
  const warning = await (await warningSaved).json()
  expect(warning.code).toBe(0)
  await expect(student.locator('.app-notification-bell .ant-badge-count')).toBeVisible({ timeout: 15000 })
  await student.getByRole('button', { name: '通知', exact: true }).click()
  await student.getByRole('listitem').filter({ hasText: '独立审计警告，请补充说明。' }).click()
  await expect(student).toHaveURL(new RegExp(`/account/decisions/${warning.data.id}$`))
  await student.getByLabel('申诉说明', { exact: true }).fill('独立审计：补充商品信息，申请重新复核。')
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAFklEQVR4nGNkYPjPwMDAxMDAwMDAAAALHwEDmIWXfgAAAABJRU5ErkJggg==', 'base64')
  await student.locator('input[type=file]').setInputFiles({ name: 'evidence.png', mimeType: 'image/png', buffer: png })
  await expect(student.getByRole('button', { name: '提交申诉', exact: true })).toBeEnabled()
  const appealSaved = student.waitForResponse(response => response.url().endsWith(`/account/decisions/${warning.data.id}/appeal`))
  await student.getByRole('button', { name: '提交申诉', exact: true }).click()
  const warningAppealId = (await (await appealSaved).json()).data.id
  await student.reload()
  await expect(student.getByText('待复核', { exact: true })).toBeVisible()
  await userDialog.getByRole('button', { name: '关闭', exact: true }).click()
  await admin.getByRole('button', { name: '通知', exact: true }).click()
  await expect(admin.getByRole('listitem').filter({ hasText: `处理记录 #${warning.data.id}` })).toBeVisible({ timeout: 15000 })
  await admin.getByRole('listitem').filter({ hasText: `处理记录 #${warning.data.id}` }).click()
  const reviewDialog = admin.getByRole('dialog', { name: '账号申诉复核', exact: true })
  await expect(reviewDialog.locator('img[src^="blob:"]')).toBeVisible()
  await reviewDialog.getByLabel('复核结论', { exact: true }).click()
  await admin.getByRole('option', { name: '撤销原处理', exact: true }).click()
  await reviewDialog.getByLabel('复核说明', { exact: true }).fill('独立审计：核实通过，撤销警告。')
  await reviewDialog.getByRole('button', { name: '确认复核并通知用户', exact: true }).click()
  await expect(reviewDialog.getByText('已撤销原处理', { exact: true })).toBeVisible()
  expect(new URL(admin.url()).searchParams.get('appeal')).toBe(String(warningAppealId))
  await student.reload()
  await expect(student.getByText('已撤销原处理', { exact: true })).toBeVisible()

  await admin.goto('/admin/users')
  if (last > 1) await admin.locator(`.ant-pagination-item-${last}`).click()
  await admin.getByRole('button', { name: `详情与人工处理 #${userId}`, exact: true }).click()
  await userDialog.getByLabel('相关行为与事实', { exact: true }).fill('独立审计：模拟需要禁用的违规行为。')
  await userDialog.getByLabel('处理依据', { exact: true }).fill('独立审计规则。')
  await userDialog.getByLabel('状态变更原因', { exact: true }).fill('独立审计禁用。')
  const disabledSaved = admin.waitForResponse(response => response.url() === `${auditApi}/admin/users/${userId}/decisions` && response.request().method() === 'POST')
  await userDialog.getByRole('button', { name: '禁用账号并撤销会话', exact: true }).click()
  const disabled = (await (await disabledSaved).json()).data
  const disabledDialog = student.getByRole('dialog', { name: '账号已被禁用', exact: true })
  await expect(disabledDialog).toBeVisible({ timeout: 15000 })
  await expect(disabledDialog.getByRole('button')).toHaveCount(2)
  await disabledDialog.getByRole('button', { name: '申诉', exact: true }).click()
  await student.getByRole('link', { name: '查看详情与申诉', exact: true }).first().click()
  await expect(student).toHaveURL(new RegExp(`/account/decisions/${disabled.id}$`))
  await student.getByLabel('申诉说明', { exact: true }).fill('独立审计：请复核本次禁用。')
  const disabledAppealSaved = student.waitForResponse(response => response.url().endsWith(`/account/decisions/${disabled.id}/appeal`))
  await student.getByRole('button', { name: '提交申诉', exact: true }).click()
  const disabledAppeal = (await (await disabledAppealSaved).json()).data
  await admin.goto(`/admin/appeals?appeal=${disabledAppeal.id}`)
  await reviewDialog.getByLabel('复核结论', { exact: true }).click()
  await admin.getByRole('option', { name: '撤销原处理', exact: true }).click()
  await reviewDialog.getByLabel('复核说明', { exact: true }).fill('独立审计：解除禁用。')
  await reviewDialog.getByRole('button', { name: '确认复核并通知用户', exact: true }).click()
  await expect(reviewDialog.getByText('已撤销原处理', { exact: true })).toBeVisible()
  await student.getByRole('button', { name: '刷新复核进度', exact: true }).click()
  await expect(student.getByText('已撤销原处理', { exact: true })).toBeVisible()
  await student.getByRole('button', { name: '返回登录', exact: true }).click()
  await student.getByLabel('校园邮箱', { exact: true }).fill(email)
  await student.getByLabel('密码', { exact: true }).fill(password)
  await student.getByRole('button', { name: '登录', exact: true }).click()
  await expect(student).toHaveURL(/\/market$/)
  expect(errors).toEqual([])
  await studentContext.close(); await adminContext.close()
})
