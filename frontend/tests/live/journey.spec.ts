  const sellerContext = await browser.newContext()
  const buyer = await buyerContext.newPage(), seller = await sellerContext.newPage()
  const errors: string[] = []
  for (const page of [buyer, seller]) page.on('pageerror', (error) => errors.push(error.name))
  await register(seller, 'Seller')
  await seller.getByRole('button', { name: '发布商品', exact: true }).click()
  const title = `UI Book ${randomUUID().slice(0, 8)}`
  await seller.getByLabel('商品名称', { exact: true }).fill(title)
  const uploaded = seller.waitForResponse((response) => response.url().includes('/uploads/images') && response.request().method() === 'POST')
  await seller.locator('input[type=file]').setInputFiles({ name: 'demo.png', mimeType: 'image/png', buffer: image })
