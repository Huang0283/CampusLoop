test('guest browse, failure recovery, secure reload restoration, logout and fixed navigation', async ({ page }) => {
  await page.goto('/market')
  await expect(page.getByRole('heading', { name: '校园市场' })).toBeVisible()
  await expect(page.getByRole('link', { name: '登录', exact: true })).toBeVisible()
  const side = await page.locator('.app-sidebar').boundingBox()
  await page.getByRole('menuitem', { name: '求购' }).click()
  expect(await page.locator('.app-sidebar').boundingBox()).toEqual(side)
  await page.route('**/products**', (route) => route.abort())
  await page.getByRole('menuitem', { name: '首页' }).click()
  await expect(page.getByRole('button', { name: /重\s*试/ })).toBeVisible()
  await page.unroute('**/products**')
  await page.getByRole('button', { name: /重\s*试/ }).click()
  await expect(page.getByRole('button', { name: /重\s*试/ })).not.toBeVisible()
  await register(page, 'Reload test')
  await page.reload()
  await expect(page.getByText('Reload test', { exact: true })).toBeVisible()
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: '个人资料' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '个人资料' })).toBeVisible()
  let expired = false
  await page.route('**/users/me', (route) => {
    if (!expired) { expired = true; return route.fulfill({ status: 401, json: { code: 'AUTH_UNAUTHORIZED', message: 'Expired fixture', requestId: 'safe-test' } }) }
    return route.continue()
  })
  await page.getByRole('menuitem', { name: '首页' }).click()
  const renewed = page.waitForResponse((response) => response.url().endsWith('/auth/browser-session') && response.status() === 200)
  await page.getByText('Reload test', { exact: true }).hover()
  await page.getByRole('menuitem', { name: '个人中心' }).click()
  await renewed
  await expect(page.getByRole('heading', { name: '个人资料' })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存资料' })).toBeVisible()
  await page.unroute('**/users/me')
  expect(await page.evaluate(() => Object.keys(localStorage).filter((key) => /token|auth|session/i.test(key)))).toEqual([])
  expect(await page.evaluate(() => document.cookie)).not.toMatch(/campusloop.*session/)
  const cookies = await page.context().cookies()
  const session = cookies.find((cookie) => /campusloop.*session/.test(cookie.name))
  expect(session?.httpOnly).toBe(true)
  expect(session?.sameSite).toBe('Strict')
  await page.getByText('Reload test', { exact: true }).hover()
  await page.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(page.getByRole('link', { name: '登录', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: '登录', exact: true })).toBeVisible()
})

