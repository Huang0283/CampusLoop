  const productPath = new URL(seller.url()).pathname
  await register(buyer, 'Buyer')
  await buyer.getByRole('searchbox', { name: '搜索商品', exact: true }).fill(title)
  await buyer.getByRole('searchbox', { name: '搜索商品', exact: true }).press('Enter')
